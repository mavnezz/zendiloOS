use std::fs;
use std::path::Path;

use super::*;

const UUID: &str = "5f1c2a3b-0d4e-4f5a-8b6c-7d8e9f0a1b2c";

/// GRUB's configuration as Debian 13's `grub-mkconfig` writes it, for
/// `kernels` newest first: `00_header` with `GRUB_DEFAULT=saved` (or
/// `GRUB_DEFAULT=0`), the first entry, the advanced options with each
/// kernel and its recovery mode, another system's found by os-prober and
/// the firmware's settings.
pub(crate) fn grub_cfg(kernels: &[&str], saved: bool) -> String {
    let default = if saved { "${saved_entry}" } else { "0" };
    let mut text = format!(
        "#\n# DO NOT EDIT THIS FILE\n#\n### BEGIN /etc/grub.d/00_header ###\n\
         if [ -s $prefix/grubenv ]; then\n  set have_grubenv=true\n  load_env\nfi\n\
         if [ \"${{next_entry}}\" ] ; then\n   set default=\"${{next_entry}}\"\n   set next_entry=\n   \
         save_env next_entry\n   set boot_once=true\nelse\n   set default=\"{default}\"\nfi\n\n\
         if [ x\"${{feature_menuentry_id}}\" = xy ]; then\n  menuentry_id_option=\"--id\"\nelse\n  \
         menuentry_id_option=\"\"\nfi\n\nexport menuentry_id_option\n\n\
         function savedefault {{\n  if [ -z \"${{boot_once}}\" ]; then\n    saved_entry=\"${{chosen}}\"\n    \
         save_env saved_entry\n  fi\n}}\n\
         function load_video {{\n  if [ x$feature_all_video_module = xy ]; then\n    insmod all_video\n  \
         else\n    insmod efi_gop\n  fi\n}}\n### END /etc/grub.d/00_header ###\n\n\
         ### BEGIN /etc/grub.d/10_linux ###\nfunction gfxmode {{\n\tset gfxpayload=\"${{1}}\"\n}}\n"
    );
    let body = |kernel: &str, options: &str, tabs: &str| {
        format!(
            "{tabs}\tload_video\n{tabs}\tinsmod gzio\n\
             {tabs}\tif [ x$grub_platform = xxen ]; then insmod xzio; insmod lzopio; fi\n\
             {tabs}\tsearch --no-floppy --fs-uuid --set=root {UUID}\n\
             {tabs}\techo\t'Loading Linux {kernel} ...'\n\
             {tabs}\tlinux\t/boot/vmlinuz-{kernel} root=UUID={UUID} ro {options}\n\
             {tabs}\techo\t'Loading initial ramdisk ...'\n\
             {tabs}\tinitrd\t/boot/initrd.img-{kernel}\n{tabs}}}\n"
        )
    };
    if let Some(first) = kernels.first() {
        text.push_str(&format!(
            "menuentry 'Debian GNU/Linux' --class debian --class gnu-linux --class gnu --class os \
             $menuentry_id_option 'gnulinux-simple-{UUID}' {{\n"
        ));
        text.push_str(&body(first, " quiet", ""));
        text.push_str(&format!(
            "submenu 'Advanced options for Debian GNU/Linux' $menuentry_id_option 'gnulinux-advanced-{UUID}' {{\n"
        ));
        for kernel in kernels {
            text.push_str(&format!(
                "\tmenuentry 'Debian GNU/Linux, with Linux {kernel}' --class debian --class gnu-linux \
                 --class gnu --class os $menuentry_id_option 'gnulinux-{kernel}-advanced-{UUID}' {{\n"
            ));
            text.push_str(&body(kernel, " quiet", "\t"));
            text.push_str(&format!(
                "\tmenuentry 'Debian GNU/Linux, with Linux {kernel} (recovery mode)' --class debian \
                 $menuentry_id_option 'gnulinux-{kernel}-recovery-{UUID}' {{\n"
            ));
            text.push_str(&body(kernel, "single", "\t"));
        }
        text.push_str("}\n");
    }
    text.push_str(
        "### END /etc/grub.d/10_linux ###\n\n### BEGIN /etc/grub.d/30_os-prober ###\n\
         menuentry 'Ubuntu 26.04 (on /dev/sdb2)' --class gnu-linux $menuentry_id_option \
         'osprober-gnulinux-simple-0a0b' {\n\tlinux /boot/vmlinuz-9.0.0-1-generic root=/dev/sdb2\n}\n\
         ### END /etc/grub.d/30_os-prober ###\n\n### BEGIN /etc/grub.d/30_uefi-firmware ###\n\
         if [ \"$grub_platform\" = \"efi\" ]; then\n\tfwsetup --is-supported\n\tif [ \"$?\" = 0 ]; then\n\
         \t\tmenuentry 'UEFI Firmware Settings' $menuentry_id_option 'uefi-firmware' {\n\t\t\tfwsetup\n\t\t}\n\
         \tfi\nfi\n### END /etc/grub.d/30_uefi-firmware ###\n",
    );
    text
}

/// The entry that starts `kernel` and nothing else.
pub(crate) fn entry_of(kernel: &str) -> String {
    format!("gnulinux-advanced-{UUID}>gnulinux-{kernel}-advanced-{UUID}")
}

/// A machine in `root`: `/boot/grub` with GRUB's configuration for
/// `kernels` (newest first), each kernel's modules, with ZFS for those in
/// `with_zfs`; `grub-editenv` writes the environment block as GRUB's does
/// and notes each call in `editenv.log`; dpkg orders versions as dpkg
/// does for these (by `sort -V`).
pub(crate) fn machine(root: &Path, kernels: &[&str], with_zfs: &[&str]) -> Boot {
    let boot = root.join("boot");
    fs::create_dir_all(boot.join("grub")).unwrap();
    fs::write(boot.join("grub/grub.cfg"), grub_cfg(kernels, true)).unwrap();
    let modules = root.join("modules");
    for kernel in kernels {
        fs::create_dir_all(modules.join(kernel).join("updates/dkms")).unwrap();
        fs::write(modules.join(kernel).join("modules.dep"), "").unwrap();
        fs::write(boot.join(format!("vmlinuz-{kernel}")), "").unwrap();
    }
    for kernel in with_zfs {
        fs::write(modules.join(kernel).join("updates/dkms/zfs.ko.xz"), "").unwrap();
    }
    // Beside Debian's other stand-ins (the runner's tests), not in their place.
    let tools = root.join("grub-tools");
    fs::create_dir_all(&tools).unwrap();
    let script = |name: &str, body: &str| {
        let path = tools.join(name);
        fs::write(&path, format!("#!/bin/sh\n{body}\n")).unwrap();
        fs::set_permissions(&path, std::os::unix::fs::PermissionsExt::from_mode(0o755)).unwrap();
        path
    };
    let log = root.join("editenv.log");
    let grub_editenv = script(
        "grub-editenv",
        &format!(
            "echo \"$*\" >> {}\n[ -e {}/editenv-fails ] && {{ echo 'cannot write' >&2; exit 1; }}\n\
             [ \"$2\" = set ] || exit 64\nprintf '# GRUB Environment Block\\n%s\\n' \"$3\" > \"$1\"",
            log.display(),
            root.display()
        ),
    );
    let dpkg = script(
        "dpkg",
        "[ \"$1\" = --compare-versions ] && [ \"$3\" = gt ] || exit 64\n\
         [ \"$2\" != \"$4\" ] && [ \"$(printf '%s\\n%s\\n' \"$2\" \"$4\" | sort -V | tail -n 1)\" = \"$2\" ]",
    );
    Boot { boot, modules, grub_editenv, dpkg }
}

fn saved(boot: &Boot) -> Option<String> {
    saved_entry(&fs::read_to_string(boot.boot.join("grub/grubenv")).unwrap_or_default())
}

fn edits(root: &Path) -> usize {
    fs::read_to_string(root.join("editenv.log")).unwrap_or_default().lines().count()
}

#[test]
fn grub_starts_the_newest_kernel_that_has_its_zfs_module() {
    let root = tempfile::tempdir().unwrap();
    let (old, new) = ("6.12.48+deb13-amd64", "6.12.57+deb13-amd64");
    let boot = machine(root.path(), &[new, old], &[old, new]);
    let chosen = boot.choose();
    assert_eq!(chosen, BootKernel { kernel: Some(new.into()), reason: BootReason::Newest, detail: None });
    assert_eq!(saved(&boot), Some(entry_of(new)), "pinned by its own entry, not the first one");
    assert_eq!(edits(root.path()), 1);
    // Chosen again, nothing is written: it is saved already.
    boot.choose();
    assert_eq!(edits(root.path()), 1);
}

#[test]
fn a_newer_kernel_without_zfs_is_not_started_until_it_has_its_module() {
    let root = tempfile::tempdir().unwrap();
    let (old, new) = ("6.12.48+deb13-amd64", "6.12.57+deb13-amd64");
    let boot = machine(root.path(), &[old], &[old]);
    assert_eq!(boot.choose().kernel.as_deref(), Some(old));

    // The new kernel installed, DKMS failed for it; GRUB's configuration
    // lists it first.
    machine(root.path(), &[new, old], &[old]);
    let chosen = boot.choose();
    assert_eq!((chosen.kernel.as_deref(), chosen.reason), (Some(old), BootReason::NewestLacksZfs));
    assert_eq!(saved(&boot), Some(entry_of(old)));

    // Built later: it starts.
    fs::write(boot.modules.join(new).join("updates/dkms/zfs.ko.xz"), "").unwrap();
    let chosen = boot.choose();
    assert_eq!((chosen.kernel.as_deref(), chosen.reason), (Some(new), BootReason::Newest));
    assert_eq!(saved(&boot), Some(entry_of(new)));
}

#[test]
fn kernels_are_ordered_as_dpkg_orders_their_versions_not_as_grub_lists_them() {
    let root = tempfile::tempdir().unwrap();
    let (old, new) = ("6.9.12+bpo-amd64", "6.12.57+deb13-amd64");
    // Listed in the other order, the older first.
    let boot = machine(root.path(), &[old, new], &[old]);
    let chosen = boot.choose();
    assert_eq!((chosen.kernel.as_deref(), chosen.reason), (Some(old), BootReason::NewestLacksZfs));
}

#[test]
fn without_any_zfs_module_the_newest_kernel_starts() {
    let root = tempfile::tempdir().unwrap();
    let (old, new) = ("6.12.48+deb13-amd64", "6.12.57+deb13-amd64");
    let boot = machine(root.path(), &[new, old], &[]);
    let chosen = boot.choose();
    assert_eq!((chosen.kernel.as_deref(), chosen.reason), (Some(new), BootReason::NoZfs));
    assert_eq!(saved(&boot), Some(entry_of(new)));
}

#[test]
fn the_pinned_kernel_removed_the_choice_follows() {
    let root = tempfile::tempdir().unwrap();
    let (old, new, newer) = ("6.12.48+deb13-amd64", "6.12.57+deb13-amd64", "6.12.60+deb13-amd64");
    let boot = machine(root.path(), &[newer, new, old], &[old, new]);
    assert_eq!(boot.choose().kernel.as_deref(), Some(new));
    // apt's autoremove takes 6.12.57 away (its hook chooses again): GRUB
    // would start the first entry, the one without ZFS.
    fs::write(boot.boot.join("grub/grub.cfg"), grub_cfg(&[newer, old], true)).unwrap();
    fs::remove_dir_all(boot.modules.join(new)).unwrap();
    let chosen = boot.choose();
    assert_eq!((chosen.kernel.as_deref(), chosen.reason), (Some(old), BootReason::NewestLacksZfs));
    assert_eq!(saved(&boot), Some(entry_of(old)));
}

#[test]
fn grub_without_the_saved_default_is_told_and_set_all_the_same() {
    let root = tempfile::tempdir().unwrap();
    let kernel = "6.12.57+deb13-amd64";
    let boot = machine(root.path(), &[kernel], &[kernel]);
    fs::write(boot.boot.join("grub/grub.cfg"), grub_cfg(&[kernel], false)).unwrap();
    let chosen = boot.choose();
    assert_eq!((chosen.kernel, chosen.reason), (None, BootReason::NotSaved));
    assert!(chosen.detail.unwrap().contains("update-grub"));
    assert_eq!(saved(&boot), Some(entry_of(kernel)), "in force once update-grub ran");
}

#[test]
fn a_machine_without_grub_is_left_alone() {
    let root = tempfile::tempdir().unwrap();
    let kernel = "6.12.57+deb13-amd64";
    let boot = machine(root.path(), &[kernel], &[kernel]);
    fs::remove_file(boot.boot.join("grub/grub.cfg")).unwrap();
    let chosen = boot.choose();
    assert_eq!((chosen.kernel.clone(), chosen.reason), (None, BootReason::NotGrub));
    assert!(said(&chosen).starts_with("no kernel chosen"), "{}", said(&chosen));
    // GRUB's configuration without a kernel of Debian's.
    fs::write(boot.boot.join("grub/grub.cfg"), grub_cfg(&[], true)).unwrap();
    assert_eq!(boot.choose().reason, BootReason::NotGrub);
    // grub-editenv missing.
    fs::write(boot.boot.join("grub/grub.cfg"), grub_cfg(&[kernel], true)).unwrap();
    let missing = Boot { grub_editenv: root.path().join("nowhere"), ..boot.clone() };
    assert_eq!(missing.choose().reason, BootReason::NotGrub);
    assert_eq!(edits(root.path()), 0);
}

#[test]
fn a_failure_to_save_is_told() {
    let root = tempfile::tempdir().unwrap();
    let kernel = "6.12.57+deb13-amd64";
    let boot = machine(root.path(), &[kernel], &[kernel]);
    fs::write(root.path().join("editenv-fails"), "").unwrap();
    let chosen = boot.choose();
    assert_eq!((chosen.kernel.clone(), chosen.reason), (None, BootReason::Failed));
    assert!(said(&chosen).contains("cannot write"), "{}", said(&chosen));
}

#[test]
fn only_the_entries_that_start_one_kernel_count() {
    let kernel = "6.12.57+deb13-amd64";
    let found = entries(&grub_cfg(&[kernel, "6.12.48+deb13-amd64"], true));
    assert_eq!(
        found,
        vec![
            Entry { kernel: kernel.into(), path: entry_of(kernel) },
            Entry { kernel: "6.12.48+deb13-amd64".into(), path: entry_of("6.12.48+deb13-amd64") },
        ],
        "not the first entry, no recovery mode, not another system's"
    );
    // GRUB_DISABLE_SUBMENU=y: the kernels' entries on the top level.
    let flat = format!(
        "menuentry 'Debian GNU/Linux, with Linux {kernel}' $menuentry_id_option 'gnulinux-{kernel}-advanced-{UUID}' {{\n\
         \tlinux\t/vmlinuz-{kernel} root=/dev/sda1 ro\n}}\n"
    );
    assert_eq!(
        entries(&flat),
        vec![Entry { kernel: kernel.into(), path: format!("gnulinux-{kernel}-advanced-{UUID}") }]
    );
    // A name that would lead out of the modules' folder is no kernel.
    let odd = flat.replace(kernel, "..");
    assert!(entries(&odd).is_empty());
}

#[test]
fn grubs_words_are_split_as_its_shell_does() {
    assert_eq!(
        words(r#"menuentry 'It'\''s "here"' --id "a\"b" plain\ word # a comment"#),
        vec!["menuentry", "It's \"here\"", "--id", "a\"b", "plain word"]
    );
    assert!(words("   ").is_empty());
    assert!(follows_saved_entry("else\n   set default=\"${saved_entry}\"\nfi\n"));
    assert!(!follows_saved_entry("   set default=\"0\"\n"));
    assert_eq!(saved_entry("# GRUB Environment Block\nsaved_entry=a>b\n####"), Some("a>b".into()));
}

#[test]
fn zfs_is_found_where_dkms_puts_it() {
    let kernel = tempfile::tempdir().unwrap();
    assert!(!has_zfs(kernel.path()));
    fs::create_dir_all(kernel.path().join("updates/dkms")).unwrap();
    fs::write(kernel.path().join("updates/dkms/zfs.ko.xz"), "").unwrap();
    assert!(has_zfs(kernel.path()));
}
