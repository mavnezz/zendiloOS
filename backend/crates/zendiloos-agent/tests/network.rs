#[tokio::test]
async fn only_existing_interfaces_and_only_with_networkd() {
    let host = Host::new();
    let agent = host.agent().await;
    let mut other = apply("192.168.1.10", 30);
    if let Request::ApplyNetwork { config, .. } = &mut other {
        config.interface = InterfaceName::parse("eth9").unwrap();
    }
    assert!(matches!(agent.execute(&other).await, Response::Error { code: ErrorCode::Forbidden, .. }));

    let unmanaged = Host::new();
    fs::remove_file(unmanaged.root.join("networkd")).unwrap();
    let agent = unmanaged.agent().await;
    let refused = agent.execute(&apply("192.168.1.10", 30)).await;
    assert!(matches!(refused, Response::Error { code: ErrorCode::Forbidden, .. }), "{refused:?}");
    assert!(unmanaged.file("05-zendiloos-enp1s0.network").is_none());
    // Neither networkd nor ifupdown: nothing to take over.
    assert_eq!(state(&agent).await, (false, None, None));
}

/// ifupdown's files go to zendiloosd as they are, a link among them only
/// named: it may lead out of `/etc/network`.
#[tokio::test]
async fn ifupdowns_files_are_handed_over_as_they_are() {
    let host = Host::with_ifupdown();
    fs::write(host.root.join("etc-network/interfaces.d/enp2s0"), "iface enp2s0 inet dhcp\n").unwrap();
    std::os::unix::fs::symlink("/etc/shadow", host.root.join("etc-network/interfaces.d/a-link")).unwrap();
    let agent = host.agent().await;
    let (managed, pending, ifupdown) = state(&agent).await;
    assert!(!managed && pending.is_none());
    let ifupdown = ifupdown.unwrap();
    assert!(ifupdown.active && ifupdown.resolved_installed);
    let files: Vec<(&str, &str, Option<&str>)> =
        ifupdown.files.iter().map(|f| (f.path.as_str(), f.text.as_str(), f.skipped.as_deref())).collect();
    assert_eq!(
        files,
        [
            ("interfaces", INTERFACES, None),
            ("interfaces.d/a-link", "", Some("a link")),
            ("interfaces.d/enp2s0", "iface enp2s0 inet dhcp\n", None),
        ]
    );
    assert_eq!(digest(&agent).await, ifupdown.digest, "the same files, the same digest");
    fs::write(host.root.join("etc-network/interfaces.d/enp2s0"), "iface enp2s0 inet manual\n").unwrap();
    assert_ne!(digest(&agent).await, ifupdown.digest);
}

#[tokio::test]
async fn the_network_is_taken_over_and_kept_once_confirmed() {
    let host = Host::with_ifupdown();
    let agent = host.agent().await;
    let seen = digest(&agent).await;
    host.forget_calls();

    assert_eq!(agent.execute(&take_over(&seen)).await, Response::Done);

    let written = host.file("05-zendiloos-enp1s0.network").unwrap();
    assert!(written.contains("DHCP=ipv4\n"), "{written}");
    assert!(
        written.contains("[DHCPv4]\nClientIdentifier=mac\nUseDomains=yes\nRequestAddress=192.168.1.127\n")
    );
    let interfaces = host.read("etc-network/interfaces").unwrap();
    assert!(interfaces.ends_with("\nauto lo\niface lo inet loopback\n"), "{interfaces}");
    assert!(!interfaces.contains("enp1s0") && !interfaces.contains("source"), "{interfaces}");
    assert_eq!(host.read("etc-network/interfaces.zendiloos-previous").as_deref(), Some(INTERFACES));
    assert_eq!(
        fs::read_link(host.root.join("resolv.conf")).unwrap(),
        Path::new("../run/systemd/resolve/stub-resolv.conf")
    );
    assert_eq!(host.read("resolv.conf.zendiloos-previous").as_deref(), Some(RESOLV_CONF));
    let record = host.root.join("etc-network/zendiloos-takeover.json");
    assert_eq!(fs::metadata(&record).unwrap().permissions().mode() & 0o777, 0o600);
    // ifupdown let go before systemd-networkd took the cards.
    assert_eq!(
        host.systemd(),
        [
            "stop networking.service ifup@*.service",
            "enable --now systemd-resolved.service",
            "enable --now systemd-networkd.socket systemd-networkd.service",
        ]
    );
    let (managed, pending, _) = state(&agent).await;
    assert!(managed);
    assert_eq!(
        pending,
        Some(NetworkChange::Takeover { interfaces: vec![InterfaceName::parse("enp1s0").unwrap()] })
    );
    let busy = agent.execute(&apply("192.168.1.10", 30)).await;
    assert!(matches!(busy, Response::Error { code: ErrorCode::Conflict, .. }), "{busy:?}");

    assert_eq!(agent.execute(&Request::ConfirmNetwork {}).await, Response::Done);
    assert!(!exists(&record), "confirmed: nothing to go back to");
    assert_eq!(
        host.read("etc-network/interfaces.zendiloos-previous").as_deref(),
        Some(INTERFACES),
        "kept for people"
    );
    assert_eq!(state(&agent).await.1, None);
    drop(agent);
    let _restarted = host.agent().await;
    assert!(host.running("networkd") && host.file("05-zendiloos-enp1s0.network").is_some(), "it stays");
}

/// Not confirmed before the agent (or the machine) restarts: ifupdown gets
/// everything back, after systemd-networkd dropped what it set.
#[tokio::test]
async fn an_unconfirmed_takeover_gives_the_network_back_to_ifupdown() {
    let host = Host::with_ifupdown();
    let agent = host.agent().await;
    let seen = digest(&agent).await;
    assert_eq!(agent.execute(&take_over(&seen)).await, Response::Done);
    drop(agent);
    host.forget_calls();

    let agent = host.agent().await;

    host.assert_ifupdown_as_it_was();
    let networkd = host.networkd();
    assert_eq!(&networkd[..3], ["Reload", "GetLinkByName s enp1s0", "ReconfigureLink i 2"], "{networkd:?}");
    assert_eq!(
        host.systemd(),
        [
            "stop systemd-networkd.service systemd-networkd*.socket",
            "disable systemd-networkd.service systemd-networkd.socket",
            "stop systemd-resolved.service systemd-resolved*.socket",
            "disable systemd-resolved.service",
            "restart networking.service",
        ]
    );
    let (managed, pending, ifupdown) = state(&agent).await;
    assert!(!managed && pending.is_none() && ifupdown.is_some_and(|i| i.digest == seen));
    // And once more, as a new takeover.
    assert_eq!(agent.execute(&take_over(&seen)).await, Response::Done);
}

/// Each place a takeover may stop at, by a power cut say, goes back from
/// the record alone, and a revert cut off is done again.
#[tokio::test]
async fn going_back_works_from_wherever_the_takeover_got_to() {
    type Cut = fn(&Host);
    let cuts: [(&str, Cut); 4] = [
        ("right after the record", |host| {
            // Nothing else changed yet.
            fs::write(host.root.join("etc-network/interfaces"), INTERFACES).unwrap();
            fs::remove_file(host.root.join("resolv.conf")).unwrap();
            fs::write(host.root.join("resolv.conf"), RESOLV_CONF).unwrap();
            for gone in ["network/05-zendiloos-enp1s0.network", "networkd", "resolved"] {
                let _ = fs::remove_file(host.root.join(gone));
            }
            let _ = fs::remove_file(host.root.join("etc-network/interfaces.zendiloos-previous"));
            fs::write(host.root.join("networking"), "").unwrap();
        }),
        ("with ifupdown stopped, before systemd-networkd", |host| {
            for gone in ["networkd", "resolved", "networking"] {
                let _ = fs::remove_file(host.root.join(gone));
            }
        }),
        ("with systemd-networkd running", |_| {}),
        ("halfway back", |host| {
            // A revert put the files back and was cut off before the record went.
            fs::write(host.root.join("etc-network/interfaces"), INTERFACES).unwrap();
            fs::remove_file(host.root.join("network/05-zendiloos-enp1s0.network")).unwrap();
            fs::remove_file(host.root.join("networkd")).unwrap();
        }),
    ];
    for (place, cut) in cuts {
        let host = Host::with_ifupdown();
        let agent = host.agent().await;
        let seen = digest(&agent).await;
        assert_eq!(agent.execute(&take_over(&seen)).await, Response::Done, "{place}");
        drop(agent);
        cut(&host);

        let _restarted = host.agent().await;
        host.assert_ifupdown_as_it_was();
        assert!(host.systemd().contains(&"restart networking.service".to_owned()), "{place}");
        // Nothing left to do at the next start.
        host.forget_calls();
        let _again = host.agent().await;
        assert!(host.systemd().is_empty(), "{place}: {:?}", host.systemd());
    }
}

/// A takeover that fails halfway goes back at once, a `resolv.conf` that
/// was a link returns as that link, and one that was missing is missing
/// again.
#[tokio::test]
async fn a_takeover_that_fails_goes_back_at_once() {
    let host = Host::with_ifupdown();
    fs::remove_file(host.root.join("resolv.conf")).unwrap();
    std::os::unix::fs::symlink("../run/resolvconf/resolv.conf", host.root.join("resolv.conf")).unwrap();
    fs::write(host.root.join("networkd-fails"), "").unwrap();
    let agent = host.agent().await;
    let seen = digest(&agent).await;

    let failed = agent.execute(&take_over(&seen)).await;
    assert!(matches!(failed, Response::Error { .. }), "{failed:?}");

    assert_eq!(
        fs::read_link(host.root.join("resolv.conf")).unwrap(),
        Path::new("../run/resolvconf/resolv.conf")
    );
    assert_eq!(host.read("etc-network/interfaces").as_deref(), Some(INTERFACES));
    assert!(host.file("05-zendiloos-enp1s0.network").is_none());
    assert!(!exists(&host.root.join("etc-network/zendiloos-takeover.json")));
    assert!(host.running("networking") && !host.running("resolved"));
    assert_eq!(state(&agent).await.1, None);

    let host = Host::with_ifupdown();
    fs::remove_file(host.root.join("resolv.conf")).unwrap();
    let agent = host.agent().await;
    let seen = digest(&agent).await;
    assert_eq!(agent.execute(&take_over(&seen)).await, Response::Done);
    drop(agent);
    let _restarted = host.agent().await;
    assert!(!exists(&host.root.join("resolv.conf")), "missing before, missing again");
}

#[tokio::test]
async fn a_takeover_needs_ifupdown_running_resolved_there_and_the_files_seen() {
    let host = Host::with_ifupdown();
    let agent = host.agent().await;
    let seen = digest(&agent).await;
    let refused = |response: Response, why: &str| match response {
        Response::Error { code: ErrorCode::Forbidden, message } => {
            assert!(message.contains(why), "{message}")
        }
        other => panic!("{why}: {other:?}"),
    };

    fs::write(host.root.join("etc-network/interfaces.d/new"), "iface eth9 inet dhcp\n").unwrap();
    refused(agent.execute(&take_over(&seen)).await, "files changed");
    fs::remove_file(host.root.join("etc-network/interfaces.d/new")).unwrap();
    fs::remove_file(host.root.join("networking")).unwrap();
    refused(agent.execute(&take_over(&seen)).await, "networking.service is not running");
    fs::write(host.root.join("networking"), "").unwrap();
    fs::remove_file(host.root.join("resolved-installed")).unwrap();
    refused(agent.execute(&take_over(&seen)).await, "systemd-resolved is not installed");
    fs::write(host.root.join("resolved-installed"), "").unwrap();
    fs::remove_file(host.root.join("ifupdown")).unwrap();
    refused(agent.execute(&take_over(&seen)).await, "ifupdown does not manage");
    fs::write(host.root.join("networkd"), "").unwrap();
    refused(agent.execute(&take_over(&seen)).await, "manages the network already");
    assert_eq!(host.read("etc-network/interfaces").as_deref(), Some(INTERFACES), "nothing changed");
    assert!(host.systemd().is_empty(), "{:?}", host.systemd());
}
