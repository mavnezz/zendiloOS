//! Network configuration against a fake host: the networkd directory,
//! ifupdown's files and `/etc/resolv.conf` in a temporary directory,
//! systemd-networkd's D-Bus API (busctl) and systemd (systemctl) replaced by
//! scripts that record their arguments. systemctl keeps the units' state
//! as files beside them: `networkd`, `networking` and `resolved` while those
//! run, `ifupdown` while `networking.service` is enabled,
//! `resolved-installed` while systemd-resolved is there.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

use tempfile::TempDir;
use zendiloos_agent::config::Tools;
use zendiloos_agent::{Erasable, ErasePolicy, NetworkPaths, Operations, Paths};
use zendiloos_agent_proto::{
    ConfirmWithin, ErrorCode, FilesDigest, Ifupdown, InterfaceName, Ipv4Config, Ipv6Config, NameServers,
    NetworkChange, NetworkConfig, Prefix, Request, Response, Role, TakeoverConfigs,
};

/// What the Debian installer wrote for a card with DHCP.
const INTERFACES: &str = "source /etc/network/interfaces.d/*\n\nauto lo\niface lo inet loopback\n\n\
    allow-hotplug enp1s0\niface enp1s0 inet dhcp\n";
const RESOLV_CONF: &str = "# Generated by dhcpcd\nnameserver 192.168.1.1\n";

struct Host {
    _dir: TempDir,
    root: PathBuf,
    tools: Tools,
}

impl Host {
    /// A host managed by systemd-networkd.
    fn new() -> Self {
        let dir = tempfile::tempdir().unwrap();
        let root = fs::canonicalize(dir.path()).unwrap();
        fs::create_dir_all(root.join("network")).unwrap();
        fs::create_dir_all(root.join("etc-network/interfaces.d")).unwrap();
        let script = |name: &str, body: &str| -> PathBuf {
            let path = root.join(name);
            let log = root.join("calls.log");
            fs::write(
                &path,
                format!("#!/bin/sh\necho \"{name} $*\" >> {}\nR={}\n{body}\n", log.display(), root.display()),
            )
            .unwrap();
            fs::set_permissions(&path, fs::Permissions::from_mode(0o755)).unwrap();
            path
        };
        let any = script("tool", "");
        let systemctl = script(
            "systemctl",
            "case \"$1\" in\n\
             is-active) case \"$3\" in\n\
               systemd-networkd.service) [ -e $R/networkd ] ;;\n\
               networking.service) [ -e $R/networking ] ;;\n\
               systemd-resolved.service) [ -e $R/resolved ] ;;\n\
               *) exit 3 ;;\n\
               esac ;;\n\
             is-enabled) case \"$2\" in\n\
               networking.service) [ -e $R/ifupdown ] && echo enabled || exit 1 ;;\n\
               systemd-resolved.service) [ -e $R/resolved-installed ] || exit 1; echo disabled; exit 1 ;;\n\
               *) echo disabled; exit 1 ;;\n\
               esac ;;\n\
             stop) case \"$*\" in *networking.service*) [ -e $R/stop-fails ] && exit 1; rm -f $R/networking ;; esac\n\
               case \"$*\" in *systemd-networkd*) rm -f $R/networkd ;; esac\n\
               case \"$*\" in *systemd-resolved*) rm -f $R/resolved ;; esac ;;\n\
             restart) touch $R/networking ;;\n\
             enable) case \"$*\" in\n\
               *systemd-networkd.service*) [ -e $R/networkd-fails ] && exit 1; touch $R/networkd ;;\n\
               *systemd-resolved*) touch $R/resolved ;;\n\
               esac ;;\n\
             disable) case \"$*\" in\n\
               *systemd-networkd*) rm -f $R/networkd ;;\n\
               *systemd-resolved*) rm -f $R/resolved ;;\n\
               esac ;;\n\
             esac",
        );
        fs::write(root.join("networkd"), "").unwrap();
        let tools = Tools {
            systemd_mount: "/bin/false".into(),
            umount: "/bin/false".into(),
            rmdir: "/bin/false".into(),
            systemctl,
            // systemd-networkd knows enp1s0 only, as link 2, set up.
            busctl: script(
                "busctl",
                "case \"$5 $7\" in \"GetLinkByName enp1s0\") echo 'io 2 \"/org/freedesktop/network1/link/_32\"';; GetLinkByName*) exit 1;; esac\n\
                 [ \"$1\" = get-property ] && echo 's \"configured\"'\nexit 0",
            ),
            lsblk: any.clone(),
            smartctl: any.clone(),
            zpool: any.clone(),
            zfs: any.clone(),
            sgdisk: any.clone(),
            wipefs: any.clone(),
            udevadm: any.clone(),
            testparm: any.clone(),
            exportfs: any.clone(),
            smbcontrol: any.clone(),
            useradd: any.clone(),
            userdel: any.clone(),
            groupadd: any.clone(),
            groupdel: any.clone(),
            gpasswd: any.clone(),
            smbpasswd: any.clone(),
            timedatectl: any.clone(),
            sshd: any.clone(),
            systemd_run: any.clone(),
            docker: any.clone(),
            setsid: "/usr/bin/setsid".into(),
            openssl: "/bin/false".into(),
            nginx: "/bin/false".into(),
            rm: "/bin/false".into(),
            nft: "/bin/false".into(),
            virsh: "/bin/false".into(),
            libvirtd: "/bin/false".into(),
            qemu: "/bin/false".into(),
            systemd_tmpfiles: "/bin/false".into(),
            dockerd: any,
        };
        Self { _dir: dir, root, tools }
    }

    /// A host as the Debian installer leaves it: ifupdown brought the
    /// network up with DHCP, dhcpcd wrote `resolv.conf`, systemd-resolved
    /// is installed but off.
    fn with_ifupdown() -> Self {
        let host = Self::new();
        for marker in ["ifupdown", "networking", "resolved-installed"] {
            fs::write(host.root.join(marker), "").unwrap();
        }
        fs::remove_file(host.root.join("networkd")).unwrap();
        fs::write(host.root.join("etc-network/interfaces"), INTERFACES).unwrap();
        fs::write(host.root.join("resolv.conf"), RESOLV_CONF).unwrap();
        host
    }

    /// The agent as it starts: a new one stands for a restart.
    async fn agent(&self) -> Operations {
        let network = NetworkPaths {
            directory: self.root.join("network"),
            ifupdown: self.root.join("etc-network"),
            resolv_conf: self.root.join("resolv.conf"),
        };
        let paths = Paths { network, ..Paths::default() };
        let operations =
            Operations::with_paths(Role::System, &self.tools, Erasable::Policy(ErasePolicy::Unused), paths)
                .unwrap();
        operations.recover().await;
        operations
    }

    fn file(&self, name: &str) -> Option<String> {
        fs::read_to_string(self.root.join("network").join(name)).ok()
    }

    fn read(&self, name: &str) -> Option<String> {
        fs::read_to_string(self.root.join(name)).ok()
    }

    fn running(&self, unit: &str) -> bool {
        self.root.join(unit).exists()
    }

    fn calls(&self) -> Vec<String> {
        let log = fs::read_to_string(self.root.join("calls.log")).unwrap_or_default();
        log.lines().map(str::to_owned).collect()
    }

    /// The methods called on systemd-networkd's manager.
    fn networkd(&self) -> Vec<String> {
        let manager = "busctl call org.freedesktop.network1 /org/freedesktop/network1 org.freedesktop.network1.Manager ";
        self.calls().iter().filter_map(|l| l.strip_prefix(manager)).map(str::to_owned).collect()
    }

    /// What was asked of systemd about the network, but for looking.
    fn systemd(&self) -> Vec<String> {
        self.calls()
            .into_iter()
            .filter_map(|l| l.strip_prefix("systemctl ").map(str::to_owned))
            .filter(|l| !l.starts_with("is-") && !l.contains("zendiloos-volume"))
            .collect()
    }

    fn forget_calls(&self) {
        let _ = fs::remove_file(self.root.join("calls.log"));
    }

    /// As ifupdown left it, untouched by a takeover: the files and the
    /// units.
    fn assert_ifupdown_as_it_was(&self) {
        assert_eq!(self.read("etc-network/interfaces").as_deref(), Some(INTERFACES));
        assert_eq!(self.read("resolv.conf").as_deref(), Some(RESOLV_CONF));
        assert!(self.file("05-zendiloos-enp1s0.network").is_none(), "no systemd-networkd file stays");
        for left in [
            "etc-network/zendiloos-takeover.json",
            "etc-network/interfaces.zendiloos-previous",
            "resolv.conf.zendiloos-previous",
        ] {
            assert!(!exists(&self.root.join(left)), "{left} stays");
        }
        assert!(self.running("networking") && !self.running("networkd") && !self.running("resolved"));
    }
}

fn exists(path: &Path) -> bool {
    path.symlink_metadata().is_ok()
}

fn apply(address: &str, seconds: u16) -> Request {
    Request::ApplyNetwork {
        config: NetworkConfig {
            interface: InterfaceName::parse("enp1s0").unwrap(),
            ipv4: Ipv4Config::Static {
                address: address.parse().unwrap(),
                prefix: Prefix::new(24).unwrap(),
                gateway: Some("192.168.1.1".parse().unwrap()),
            },
            ipv6: Ipv6Config::Automatic,
            dns: NameServers::new(vec!["192.168.1.1".parse().unwrap()]).unwrap(),
        },
        confirm_within: ConfirmWithin::seconds(seconds).unwrap(),
    }
}

async fn state(agent: &Operations) -> (bool, Option<NetworkChange>, Option<Ifupdown>) {
    let Response::NetworkState { managed, pending, ifupdown, .. } =
        agent.execute(&Request::NetworkState {}).await
    else {
        panic!("no state")
    };
    (managed, pending.map(|p| p.change), ifupdown)
}

/// enp1s0 by DHCP, asking for the address it has, as zendiloosd sends it.
fn take_over(digest: &FilesDigest) -> Request {
    let config = NetworkConfig {
        interface: InterfaceName::parse("enp1s0").unwrap(),
        ipv4: Ipv4Config::Dhcp { request: Some("192.168.1.127".parse().unwrap()) },
        ipv6: Ipv6Config::Automatic,
        dns: NameServers::default(),
    };
    Request::TakeOverNetwork {
        configs: TakeoverConfigs::new(vec![config]).unwrap(),
        digest: digest.clone(),
        confirm_within: ConfirmWithin::seconds(120).unwrap(),
    }
}

async fn digest(agent: &Operations) -> FilesDigest {
    state(agent).await.2.expect("ifupdown manages the network").digest
}

#[tokio::test]
async fn a_change_waits_for_confirmation_and_goes_back_if_none_comes() {
    let host = Host::new();
    let agent = host.agent().await;

    assert_eq!(agent.execute(&apply("192.168.1.10", 120)).await, Response::Done);
    let written = host.file("05-zendiloos-enp1s0.network").unwrap();
    assert!(written.contains("Address=192.168.1.10/24"), "{written}");
    assert!(
        host.file("05-zendiloos-enp1s0.network.previous")
            .unwrap()
            .starts_with("# zendiloos: there was no file")
    );
    assert_eq!(
        host.networkd(),
        ["GetLinkByName s enp1s0", "GetLinkByName s enp1s0", "Reload", "ReconfigureLink i 2"]
    );
    let (managed, pending, ifupdown) = state(&agent).await;
    assert!(managed && ifupdown.is_none());
    assert_eq!(
        pending,
        Some(NetworkChange::Interface { interface: InterfaceName::parse("enp1s0").unwrap() })
    );
    let Response::Error { code, .. } = agent.execute(&apply("192.168.1.11", 120)).await else {
        panic!("a second change")
    };
    assert_eq!(code, ErrorCode::Conflict, "one change at a time");

    assert_eq!(agent.execute(&Request::ConfirmNetwork {}).await, Response::Done);
    assert!(host.file("05-zendiloos-enp1s0.network.previous").is_none(), "confirmed: nothing to go back to");
    assert!(matches!(agent.execute(&Request::ConfirmNetwork {}).await, Response::Error { .. }));

    // The next change is not confirmed before the agent restarts: the
    // confirmed file returns.
    assert_eq!(agent.execute(&apply("10.9.9.9", 120)).await, Response::Done);
    drop(agent);
    let _restarted = host.agent().await;
    let back = host.file("05-zendiloos-enp1s0.network").unwrap();
    assert!(back.contains("Address=192.168.1.10/24"), "{back}");
    assert!(!exists(&host.root.join("network/05-zendiloos-enp1s0.network.previous")));
}

